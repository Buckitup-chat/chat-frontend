// Generates src/lib/pq/schema.generated.ts from the backend Ecto schemas.
//
// The backend source is the contract (CLAUDE.md): the signable field set per
// relation lives in chat/lib/chat/data/schemas/*.ex, and hand-copying it here
// is exactly the drift this file removes. Run after any backend schema change:
//
//   node scripts/gen-pq-schema.mjs            # rewrites schema.generated.ts
//   node scripts/gen-pq-schema.mjs --check    # exits 1 if the file is stale
//
// The backend checkout is found via CHAT_REPO, falling back to ../chat.
// tests/pqSchemaGen.test.ts runs the --check comparison when a checkout is
// present, so a stale file fails the suite on any machine that has both repos.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const OUTPUT_PATH = path.join(HERE, '..', 'src', 'lib', 'pq', 'schema.generated.ts');

export const findChatRepo = () => {
	const candidates = [
		process.env.CHAT_REPO,
		path.join(HERE, '..', '..', 'chat'),
	].filter(Boolean);
	for (const c of candidates) {
		if (fs.existsSync(path.join(c, 'lib', 'chat', 'data', 'schemas'))) return c;
	}
	return null;
};

// The relations this client signs or verifies. Backend-only schemas (reviews,
// origins, upload bookkeeping) are deliberately absent.
const SCHEMA_FILES = [
	'user_card.ex',
	'user_storage.ex',
	'dialog_key.ex',
	'dialog_message.ex',
	'dialog_message_version.ex',
	'dialog_message_reaction.ex',
	'dialog_message_receipt.ex',
	'file.ex',
];

const TYPE_MAP = {
	':binary': 'binary',
	':string': 'text',
	':integer': 'int',
	':boolean': 'bool',
	'{:array, :binary}': 'binary[]',
	'Ecto.UUID': 'text',
};

const mapType = (ectoType, field, file) => {
	if (ectoType in TYPE_MAP) return TYPE_MAP[ectoType];
	// Everything else is a custom Ecto type module (UserHash, DialogHash,
	// *SignHash, *Id, FileId, …) whose runtime form is a prefixed string.
	if (/^[A-Z][\w.]*$/.test(ectoType)) return 'text';
	throw new Error(`${file}: cannot map Ecto type ${ectoType} of field ${field}`);
};

const parseSchema = (source, file) => {
	const table = source.match(/^\s*schema "([\w]+)" do/m)?.[1];
	if (!table) throw new Error(`${file}: no schema block found`);

	const fields = [];
	// @primary_key {:name, Type, opts} — a column like any other, declared apart
	const pk = source.match(/@primary_key\s*\{:(\w+),\s*([\w.]+)/);
	if (pk) fields.push([pk[1], mapType(pk[2], pk[1], file)]);

	// field(:name, Type[, opts]) — Type is an atom, a module, or {:array, :atom}
	for (const m of source.matchAll(/field\(:(\w+),\s*(\{[^}]*\}|[^,)\s]+)/g)) {
		fields.push([m[1], mapType(m[2], m[1], file)]);
	}

	// sign_b64/sign_hash are never signable; the Signable impl's Map.drop may
	// name more (assoc fields like parent_version are not columns and are
	// already absent). dialog_messages_versions has no Signable impl — its rows
	// are archived dialog_messages revisions and keep that relation's rules.
	const dropped = new Set(['sign_b64', 'sign_hash']);
	const drop = source.match(/Map\.drop\(\[([^\]]+)\]\)/);
	if (drop) {
		for (const name of drop[1].split(',')) dropped.add(name.trim().replace(/^:/, ''));
	}

	return { table, fields: fields.filter(([name]) => !dropped.has(name)) };
};

export const generateSchema = (chatRepo) => {
	const dir = path.join(chatRepo, 'lib', 'chat', 'data', 'schemas');
	const relations = SCHEMA_FILES.map((f) =>
		parseSchema(fs.readFileSync(path.join(dir, f), 'utf8'), f));

	const lines = [];
	lines.push('// GENERATED by scripts/gen-pq-schema.mjs from the backend Ecto schemas —');
	lines.push('// do not edit. Regenerate after a backend schema change:');
	lines.push('//   node scripts/gen-pq-schema.mjs');
	lines.push('');
	lines.push("export type FieldType = 'text' | 'int' | 'bool' | 'binary' | 'binary[]';");
	lines.push('');
	lines.push('/** Column name → type. sign_b64 and sign_hash are never signable. */');
	lines.push('export type SignableSchema = Record<string, FieldType>;');
	lines.push('');
	lines.push('export const SIGNABLE: Record<string, SignableSchema> = {');
	for (const { table, fields } of relations) {
		lines.push(`\t${table}: {`);
		for (const [name, type] of fields) lines.push(`\t\t${name}: '${type}',`);
		lines.push('\t},');
	}
	lines.push('};');
	return lines.join('\n') + '\n';
};

const main = () => {
	const chatRepo = findChatRepo();
	if (!chatRepo) {
		console.error('backend checkout not found — set CHAT_REPO to a chat repo path');
		process.exit(2);
	}
	const generated = generateSchema(chatRepo);
	if (process.argv.includes('--check')) {
		const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, 'utf8') : '';
		if (current !== generated) {
			console.error('src/lib/pq/schema.generated.ts is stale — run node scripts/gen-pq-schema.mjs');
			process.exit(1);
		}
		console.log('schema.generated.ts matches the backend schemas');
		return;
	}
	fs.writeFileSync(OUTPUT_PATH, generated);
	console.log(`wrote ${path.relative(process.cwd(), OUTPUT_PATH)} from ${chatRepo}`);
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	main();
}
